import { capture, expect, goalAttempts, reload, scenarioScope, state, test, visit } from './fixtures';

test('canceled pending reviews leave attention while exact evidence stays inspectable', async ({ page, scenario }, testInfo) => {
  const scope = scenarioScope(scenario), title = `Canceled review ${scenario.id.slice(0, 8)}`;
  await visit(page, `/projects/${scenario.launchProject}/goals/new${scope}`);
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill(title);
  await page.getByRole('combobox', { name: 'Sendero', exact: true }).selectOption(scenario.prerequisiteVersionId);
  await page.getByRole('button', { name: 'Create goal', exact: true }).click();
  await page.getByRole('button', { name: 'Start goal', exact: true }).click();
  const goal = state().goals.find(item => item.title === title)!;
  await page.getByRole('link', { name: 'Review ready activations' }).click();
  await page.getByRole('button', { name: 'Dispatch all' }).click();
  await expect.poll(() => goalAttempts(goal.id).length).toBe(1);
  const attempt = goalAttempts(goal.id)[0]!;
  const goalPath = `/projects/${scenario.launchProject}/canvas/goals/${goal.id}/attempts/${attempt.id}${scope}`;
  await visit(page, goalPath);
  await page.getByRole('combobox', { name: 'Evidence kind', exact: true }).selectOption('manual');
  await page.getByLabel('Evidence label', { exact: true }).fill('Retained canceled review proof');
  await page.getByRole('button', { name: 'Record evidence', exact: true }).click();
  await expect(page.locator('.context-inspector')).toContainText('Retained canceled review proof');
  const pending = JSON.parse(goalAttempts(goal.id)[0]!.statusSnapshotJson);
  expect(pending.review.status).toBe('pending');
  await visit(page, `/now${scope}&filter=review`);
  await expect(page.locator('.attention-list > a')).toHaveCount(1);
  await page.locator('.attention-list > a').click();
  await expect(page.getByRole('complementary', { name: 'Selected attempt details' })).toContainText('Retained canceled review proof');
  await visit(page, goalPath);
  await page.getByRole('button', { name: 'Request stop', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm stop', exact: true }).click();
  await expect.poll(() => goalAttempts(goal.id)[0]!.status).toBe('canceled');
  const before = state();
  await visit(page, `/now${scope}&filter=review`);
  await expect(page.getByRole('heading', { name: 'No matching attention' })).toBeVisible();
  await reload(page);
  await expect(page.locator('.attention-list > a')).toHaveCount(0);
  await visit(page, `/reviews${scope}`);
  await expect(page.getByRole('link', { name: /Inspect evidence/ })).toHaveCount(1);
  await page.getByRole('link', { name: /Inspect evidence/ }).click();
  await expect(page.getByRole('complementary', { name: 'Selected attempt details' })).toContainText('Retained canceled review proof');
  await page.getByRole('link', { name: 'Open execution', exact: true }).click();
  const inspector = page.locator('.context-inspector');
  await expect(inspector).toContainText('read-only');
  await expect(inspector.getByRole('button', { name: 'Record evidence', exact: true })).toHaveCount(0);
  await expect(inspector).toContainText('Retained canceled review proof');
  await inspector.getByRole('heading', { name: 'Evidence & review', exact: true }).scrollIntoViewIfNeeded();
  await capture(page, testInfo, 'terminal-review-desktop-1440x1000');
  await page.setViewportSize({ width: 390, height: 844 });
  await inspector.getByRole('heading', { name: 'Evidence & review', exact: true }).scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await capture(page, testInfo, 'terminal-review-mobile-390x844');
  expect(JSON.parse(goalAttempts(goal.id)[0]!.statusSnapshotJson)).toMatchObject(pending);
  expect(state()).toEqual(before);
});
