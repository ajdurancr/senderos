import { capture, expect, reload, state, test, visit } from './fixtures';

test('registers a context and its standalone project, retains validation errors and selects the durable scope', async ({ page, scenario }, testInfo) => {
  const before = state();
  const contextName = `Notebook team ${scenario.id.slice(0, 8)}`;
  await visit(page, `/now?context=empty-${scenario.id}`);
  await expect(page.getByRole('heading', { name: 'No projects in this scope' })).toBeVisible();
  await page.getByRole('link', { name: 'Set up a project' }).click();
  await expect(page.getByRole('heading', { name: 'Set up a workspace' })).toBeVisible();
  await visit(page, `/settings?context=${scenario.productContext}&project=${scenario.launchProject}`);
  await page.getByText('Add an execution context', { exact: true }).click();
  const contextInput = page.getByRole('textbox', { name: /^Context name/ });
  await page.getByRole('button', { name: 'Add context', exact: true }).click();
  expect(await contextInput.evaluate((input: HTMLInputElement) => input.validity.valueMissing)).toBe(true);
  await contextInput.fill('Unsubmitted draft');
  await page.getByText('Add an execution context', { exact: true }).click();
  expect(state().executionContexts).toEqual(before.executionContexts);
  await page.getByText('Add an execution context', { exact: true }).click();
  await contextInput.fill('   ');
  await page.getByRole('button', { name: 'Add context', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Execution context name is required.');
  expect(state().executionContexts).toEqual(before.executionContexts);
  await contextInput.fill(contextName);
  await page.getByRole('button', { name: 'Add context', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Execution context added.');
  const context = state().executionContexts.find(item => item.name === contextName)!;
  expect(context).toBeTruthy();
  expect(new URL(page.url()).searchParams.get('context')).toBe(context.id);
  expect(new URL(page.url()).searchParams.has('project')).toBe(false);
  await expect(page.getByRole('heading', { name: 'No project in this scope' })).toBeVisible();
  const projectName = page.getByRole('textbox', { name: /^Project name/ });
  const projectContext = page.getByRole('combobox', { name: /^Project execution context/ });
  await expect(projectContext).toHaveValue(context.id);
  await expect(projectName).toBeVisible();
  await projectName.fill('   ');
  await page.getByRole('button', { name: 'Add project', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Project name is required.');
  expect(state().projects).toEqual(before.projects);
  await reload(page);
  await projectName.fill('Research notebook');
  await capture(page, testInfo, 'registration-ready-desktop-1440x1000');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Add project', exact: true }).scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await capture(page, testInfo, 'registration-ready-mobile-390x844');
  await page.getByRole('button', { name: 'Add project', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Project added.');
  const project = state().projects.find(item => item.name === 'Research notebook' && item.executionContextId === context.id)!;
  expect(project).toMatchObject({ integrationMode: 'none', targetBranch: '', canonicalPath: '', githubOwner: '', githubRepo: '' });
  expect(new URL(page.url()).searchParams.get('context')).toBe(context.id);
  expect(new URL(page.url()).searchParams.get('project')).toBe(project.id);
  await reload(page);
  await expect(page.getByRole('textbox', { name: /^Name\b/ })).toHaveValue('Research notebook');
  await expect(page.getByRole('textbox', { name: /^Target branch/ })).toHaveValue('');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByText('Add a project', { exact: true }).click();
  await projectName.fill('Research notebook');
  await page.getByRole('button', { name: 'Add project', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('already exists in this context');
  await expect(projectName).toHaveValue('Research notebook');
  await page.getByText('Add an execution context', { exact: true }).click();
  await contextInput.fill(contextName);
  await page.getByRole('button', { name: 'Add context', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('already in use');
  const after = state();
  expect(after.projects.filter(item => item.executionContextId === context.id)).toHaveLength(1);
  expect(after.executionContexts).toHaveLength(before.executionContexts.length + 1);
  expect(after.projects.filter(item => item.id !== project.id)).toEqual(before.projects);
  expect(after.goals).toEqual(before.goals);
  expect(after.runs).toEqual(before.runs);
  expect(after.claims).toEqual(before.claims);
});
