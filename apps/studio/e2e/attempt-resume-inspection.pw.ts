import { capture, expect, goalAttempts, ready, reload, runtime, scenarioScope, state, test, visit } from './fixtures';

for (const width of [1440, 390]) test(`inspects recorded resume guidance without executing or replaying it at ${width}px`, async ({ page, scenario }, testInfo) => {
  await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 });
  const scope = scenarioScope(scenario), title = `Resume inspection ${scenario.id}`;
  await visit(page, `/projects/${scenario.launchProject}/goals/new${scope}`);
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill(title);
  await page.getByRole('combobox', { name: 'Sendero', exact: true }).selectOption(scenario.prerequisiteVersionId);
  await page.getByRole('button', { name: 'Create goal', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Start goal', exact: true })).toBeVisible();
  const goal = state().goals.find(item => item.title === title)!;
  await page.getByRole('button', { name: 'Start goal', exact: true }).click();
  await page.getByRole('link', { name: 'Review ready activations' }).click();
  await page.getByRole('button', { name: 'Dispatch all' }).click();
  await expect.poll(() => goalAttempts(goal.id).length).toBe(1);
  const attempt = goalAttempts(goal.id)[0]!;
  runtime('host-claim', attempt.id); runtime('host-start-with-resume', attempt.id);
  runtime('host-reconcile-unknown', attempt.id);
  const before = state(), stored = before.attempts.find(item => item.id === attempt.id)!;
  expect(stored.resumeCommand).toContain(`simulated-worker-${attempt.id}`);
  const path = `/projects/${scenario.launchProject}/runs/attempts/${attempt.id}${scope}`;
  await visit(page, path);
  const runsUrl = page.url();
  const detail = page.getByRole('complementary', { name: 'Selected attempt details' });
  const records = detail.getByRole('region', { name: 'Host and session records' });
  await records.locator('summary').first().focus(); await page.keyboard.press('Enter');
  await records.getByRole('region', { name: 'Recorded resume guidance' }).scrollIntoViewIfNeeded();
  await capture(page, testInfo, `resume-runs-final-${width}`);
  expect(await records.innerText()).toContain(stored.resumeCommand!);
  await expect(records.getByRole('region', { name: 'Recovery next step' })).toContainText('Keep recovery blocked');
  await detail.getByRole('link', { name: 'Review this attempt', exact: true }).click(); await ready(page);
  const inspector = page.locator('.context-inspector');
  const executionRecords = inspector.getByRole('region', { name: 'Host and session records' });
  await executionRecords.locator('summary').first().click();
  await executionRecords.getByRole('region', { name: 'Recorded resume guidance' }).scrollIntoViewIfNeeded();
  await capture(page, testInfo, `resume-execution-final-${width}`);
  expect(await executionRecords.innerText()).toContain(stored.resumeCommand!);
  await expect(executionRecords.getByRole('region', { name: 'Recovery next step' })).toContainText('Keep recovery blocked');
  const guidance = executionRecords.getByRole('region', { name: 'Recorded resume guidance' });
  expect(await guidance.locator('pre').innerText()).toBe(stored.resumeCommand);
  await expect(guidance.locator('a, button')).toHaveCount(0);
  await expect(guidance).toContainText('does not authorize resuming');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(state()).toEqual(before);
  await page.goBack(); await ready(page); expect(page.url()).toBe(runsUrl);
  await reload(page); expect(state()).toEqual(before);
  await records.locator('summary').first().click();
  await expect(records).toContainText(stored.resumeCommand!);
  await page.getByRole('combobox', { name: 'Project', exact: true }).selectOption(scenario.campaignProject);
  await expect(page.getByRole('region', { name: 'Recorded resume guidance' })).toHaveCount(0);
  await visit(page, path);
  await records.locator('summary').first().click();
  await expect(records).toContainText(stored.resumeCommand!);
  expect(state()).toEqual(before);
  await testInfo.attach('stored-resume-readback', { body: JSON.stringify({ attemptId: attempt.id, resumeCommand: stored.resumeCommand, runsUrl }, null, 2), contentType: 'application/json' });
});
