import { capture, expect, ready, reload, runtime, scenarioScope, state, test, visit, workflowCreated } from './fixtures';
for (const width of [1440, 390]) test(`reads the recorded host result for an exact attempt at ${width}px`, async ({ page, scenario }, testInfo) => {
  await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 });
  const scope = scenarioScope(scenario), slug = `pinned-agent-${scenario.id}`;
  const originalName = `Original pinned executor ${scenario.id.slice(0, 8)}`;
  await visit(page, `/agents/new${scope}`);
  await page.getByRole('textbox', { name: /^Name\b/ }).fill(originalName);
  await page.getByRole('textbox', { name: 'Slug', exact: true }).fill(slug);
  await page.getByRole('textbox', { name: 'Instructions', exact: true }).fill('Synthetic original pinned instructions');
  await page.getByRole('button', { name: 'Create agent', exact: true }).click();
  await expect(page.getByText('Agent created.', { exact: true })).toBeVisible(); await ready(page);
  const agent = state().agents.find(item => item.slug === slug)!;
  await visit(page, `/senderos/new${scope}`);
  await page.getByRole('combobox', { name: 'Authoring method' }).selectOption('import');
  await page.getByRole('textbox', { name: 'Sendero JSON' }).fill(JSON.stringify({ slug: `pinned-inspection-${scenario.id}`, name: 'Pinned inspection audit', nodes: [
    { key: 'start', kind: 'start', label: 'Begin' },
    { key: 'worker', kind: 'agent', label: 'Inspect pinned policy', agentSlug: slug, executionObjective: 'Synthetic inspection only' },
    { key: 'end', kind: 'end', label: 'End' },
  ], edges: [{ key: 'begin', source: 'start', target: 'worker', name: 'Begin' }, { key: 'finish', source: 'worker', target: 'end', name: 'Finish' }] }));
  await page.getByRole('button', { name: 'Import draft', exact: true }).click(); await workflowCreated(page);
  const workflowId = new URL(page.url()).pathname.split('/').at(-1)!;
  await page.getByRole('button', { name: 'Validate & publish draft' }).click();
  await expect(page.getByRole('button', { name: 'Create editable draft' })).toBeVisible();
  const published = state(), version = published.versions.find(item => item.senderoId === workflowId)!;
  const node = published.nodes.find(item => item.senderoVersionId === version.id && item.kind === 'agent')!;
  expect(JSON.parse(node.agentSnapshotJson!).instructions).toBe('Synthetic original pinned instructions');
  await visit(page, `/projects/${scenario.launchProject}/goals/new${scope}`);
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill(`Result inspection goal ${scenario.id}`);
  await page.getByLabel('Category', { exact: true }).fill('feature');
  await page.getByRole('textbox', { name: 'Specification', exact: true }).fill('Synthetic inspection only');
  await page.getByRole('combobox', { name: 'Sendero', exact: true }).selectOption(version.id);
  await page.getByRole('button', { name: 'Create goal', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit goal', exact: true })).toBeVisible();
  const goal = state().goals.find(item => item.title === `Result inspection goal ${scenario.id}`)!;
  await page.getByRole('button', { name: 'Start goal', exact: true }).click();
  await page.getByRole('link', { name: 'Review ready activations', exact: true }).click();
  await page.getByRole('button', { name: 'Dispatch all', exact: true }).click();
  await expect.poll(() => state().runs.filter(item => item.goalId === goal.id).length).toBe(1);
  const run = state().runs.find(item => item.goalId === goal.id)!;
  const attempt = state().attempts.find(item => item.runId === run.id)!;
  runtime('host-claim', attempt.id); runtime('host-start', attempt.id); runtime('host-complete', attempt.id);
  const before = state();
  expect(JSON.parse(before.attempts.find(item => item.id === attempt.id)!.resultJson)).toEqual({ outcome: 'accepted', summary: 'Deterministic external execution fixture finished.' });
  const recorded = JSON.parse(before.attempts.find(item => item.id === attempt.id)!.resultJson);
  const runsUrl = `/projects/${scenario.launchProject}/runs/attempts/${attempt.id}${scope}`;
  await visit(page, runsUrl);
  const exactRunsUrl = page.url();
  const detail = page.getByRole('complementary', { name: 'Selected attempt details' });
  const result = detail.getByRole('region', { name: 'Recorded result' });
  await expect(result).toContainText(recorded.summary);
  await expect(result).toContainText(recorded.outcome);
  const complete = result.getByText('Complete recorded result', { exact: true });
  await complete.focus(); await expect(complete).toBeFocused(); await page.keyboard.press('Enter');
  await expect(result.locator('pre')).toBeVisible();
  expect(JSON.parse(await result.locator('pre').innerText())).toEqual(recorded);
  await result.scrollIntoViewIfNeeded();
  await capture(page, testInfo, `attempt-result-final-${width}`);
  await reload(page); expect(state()).toEqual(before);
  await expect(result).toContainText(recorded.summary);
  await detail.getByRole('link', { name: 'Open execution', exact: true }).focus();
  await page.keyboard.press('Enter'); await ready(page);
  await expect(page).toHaveURL(url => url.pathname.includes(attempt.id));
  const exactExecutionUrl = page.url();
  const inspector = page.locator('.context-inspector');
  const executionResult = inspector.getByRole('region', { name: 'Recorded result' });
  await expect(executionResult).toContainText(recorded.summary);
  await executionResult.getByText('Complete recorded result', { exact: true }).click();
  await expect(executionResult.locator('pre')).toBeVisible();
  expect(JSON.parse(await executionResult.locator('pre').innerText())).toEqual(recorded);
  await executionResult.scrollIntoViewIfNeeded();
  await capture(page, testInfo, `execution-result-final-${width}`);
  await testInfo.attach('exact-result-readback', { body: JSON.stringify({ recorded, runsUrl: exactRunsUrl, executionUrl: exactExecutionUrl, rendered: await executionResult.innerText() }, null, 2), contentType: 'application/json' });
  expect(state()).toEqual(before);
  await page.goBack(); await ready(page); expect(page.url()).toBe(exactRunsUrl);
  await expect(result).toContainText(recorded.summary);
  await page.goForward(); await ready(page); expect(page.url()).toBe(exactExecutionUrl);
  await reload(page); await expect(executionResult).toContainText(recorded.summary); expect(state()).toEqual(before);
  await page.getByRole('combobox', { name: 'Project', exact: true }).selectOption(scenario.campaignProject);
  await expect(page.getByRole('region', { name: 'Recorded result' })).toHaveCount(0);
  await visit(page, runsUrl); await expect(result).toContainText(recorded.summary);
  expect(state()).toEqual(before);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
