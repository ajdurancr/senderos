import { test, expect, scenarioScope, visit, ready, state, capture, runtime } from './fixtures';

test('prepares an existing draft goal before activation', async ({ page, scenario }, testInfo) => {
  const scope = scenarioScope(scenario);
  const title = `Prepare goal ${scenario.id}`;
  await visit(page, `/projects/${scenario.launchProject}/goals/new${scope}`);
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill(title);
  await page.getByRole('textbox', { name: 'Specification', exact: true }).fill('Initial acceptance');
  await page.getByRole('combobox', { name: 'Sendero', exact: true }).selectOption(scenario.prerequisiteVersionId);
  await page.getByRole('button', { name: 'Create goal', exact: true }).click();
  const goal = state().goals.find(item => item.title === title)!;
  expect(goal.status).toBe('draft');
  await page.getByRole('button', { name: 'Edit goal', exact: true }).click();
  const titleInput = page.getByRole('textbox', { name: 'Goal title', exact: true });
  await expect(titleInput).toHaveValue(title);
  const before = state();
  await titleInput.fill(' ');
  await page.getByRole('button', { name: 'Save goal draft', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('goal title');
  expect(state()).toEqual(before);
  await expect(titleInput).toHaveValue(' ');
  await page.getByRole('button', { name: 'Cancel preparation' }).click();
  expect(state()).toEqual(before);
  await page.getByRole('button', { name: 'Edit goal', exact: true }).click();
  await expect(titleInput).toHaveValue(title);
  await titleInput.fill(`Revised outcome ${scenario.id.slice(0, 8)}`);
  await page.getByLabel('Goal category', { exact: true }).fill('research');
  await page.getByLabel('Goal specification', { exact: true }).fill('Review the recorded waiting outcome before execution.');
  const alternate = state().senderos.find(item => item.slug === 'timed-wait-demo')!;
  const version = state().versions.find(item => item.senderoId === alternate.id && item.status === 'published')!;
  await page.getByLabel('Goal workflow', { exact: true }).selectOption(version.id);
  await page.getByRole('heading', { name: 'Prepare this goal' }).scrollIntoViewIfNeeded();
  await capture(page, testInfo, 'goal-preparation-desktop-1440x1000');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('heading', { name: 'Prepare this goal' }).scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await capture(page, testInfo, 'goal-preparation-mobile-390x844');
  await page.getByRole('button', { name: 'Save goal draft', exact: true }).scrollIntoViewIfNeeded();
  await capture(page, testInfo, 'goal-preparation-mobile-actions-390x844');
  await page.getByRole('button', { name: 'Save goal draft', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Goal preparation saved' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Edit goal', exact: true })).toBeVisible();
  await page.reload(); await ready(page);
  expect(state().goals.find(item => item.id === goal.id)).toMatchObject({ status: 'draft', title: `Revised outcome ${scenario.id.slice(0, 8)}`, kind: 'research', specText: 'Review the recorded waiting outcome before execution.', senderoVersionId: version.id });
  expect(state().runs.filter(item => item.goalId === goal.id)).toHaveLength(0);
  // Two real editors review the same draft, then only the first save wins.
  await page.getByRole('button', { name: 'Edit goal', exact: true }).click();
  await titleInput.fill('Retain this local proposal');
  const other = await page.context().newPage();
  await visit(other, page.url());
  await other.getByRole('button', { name: 'Edit goal', exact: true }).click();
  await other.getByLabel('Goal title', { exact: true }).fill('Accepted concurrent proposal');
  await other.getByRole('button', { name: 'Save goal draft', exact: true }).click();
  await expect(other.getByRole('button', { name: 'Edit goal', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Save goal draft', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'changed elsewhere' }).first()).toBeVisible();
  await expect(titleInput).toHaveValue('Retain this local proposal');
  expect(state().goals.find(item => item.id === goal.id)?.title).toBe('Accepted concurrent proposal');
  await page.getByRole('button', { name: 'Cancel preparation' }).click();
  await other.close();
  await page.getByRole('button', { name: 'Start goal', exact: true }).click();
  await expect.poll(() => state().goals.find(item => item.id === goal.id)?.status).toBe('active');
  await expect(page.getByRole('button', { name: 'Edit goal', exact: true })).toHaveCount(0);
  expect(state().runs.filter(item => item.goalId === goal.id)).toHaveLength(0);
});


test('assigns a workflow to an unassigned Core-created goal through Studio', async ({ page, scenario }) => {
  const goal = runtime('prepare-draft-goal', scenario.id) as { id: string };
  const scope = `?context=${scenario.productContext}&project=${scenario.campaignProject}`;
  await visit(page, `/projects/${scenario.campaignProject}/canvas/goals/${goal.id}${scope}`);
  await expect(page.getByRole('button', { name: 'Start goal', exact: true })).toBeDisabled();
  await expect(page.getByText('Choose a published Sendero in Edit goal before starting.')).toBeVisible();
  await page.getByRole('button', { name: 'Edit goal', exact: true }).click();
  await expect(page.getByLabel('Goal workflow', { exact: true })).toHaveValue('');
  await page.getByLabel('Goal workflow', { exact: true }).selectOption(scenario.prerequisiteVersionId);
  const before = state();
  await page.getByRole('combobox', { name: 'Project', exact: true }).selectOption(scenario.launchProject);
  const dialog = page.getByRole('dialog', { name: 'Leave goal editor?' });
  await expect(dialog).toBeVisible();
  await dialog.getByRole('button', { name: 'Stay here' }).click();
  await expect(page.getByLabel('Goal workflow', { exact: true })).toHaveValue(scenario.prerequisiteVersionId);
  expect(state()).toEqual(before);
  await page.getByRole('button', { name: 'Save goal draft', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Start goal', exact: true })).toBeEnabled();
  await page.reload(); await ready(page);
  expect(state().goals.find(item => item.id === goal.id)).toMatchObject({ status: 'draft', senderoVersionId: scenario.prerequisiteVersionId });
  expect(state().runs.filter(item => item.goalId === goal.id)).toHaveLength(0);
});

test('keeps preparation after unconfirmed saves and rejects a stale retry', async ({ page, scenario }) => {
  const goal = runtime('prepare-draft-goal', scenario.id) as { id: string };
  const path = `/projects/${scenario.campaignProject}/canvas/goals/${goal.id}?context=${scenario.productContext}&project=${scenario.campaignProject}`;
  await visit(page, path);
  await page.getByRole('button', { name: 'Edit goal', exact: true }).click();
  const title = page.getByLabel('Goal title', { exact: true });
  await title.fill('Preserved preparation');
  const before = state();
  await page.route('**/*.data*', route => route.request().method() === 'POST' ? route.abort('connectionfailed') : route.continue());
  await page.getByRole('button', { name: 'Save goal draft', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('could not confirm the goal save');
  await expect(title).toHaveValue('Preserved preparation');
  expect(state()).toEqual(before);
  await page.unroute('**/*.data*');
  let responseDropped!: () => void;
  const dropped = new Promise<void>(resolve => { responseDropped = resolve; });
  await page.route('**/*.data*', async route => {
    if (route.request().method() === 'POST') { await route.fetch(); await route.abort('connectionfailed'); responseDropped(); }
    else await route.continue();
  });
  await page.getByRole('button', { name: 'Save goal draft', exact: true }).click();
  await dropped;
  await expect(page.getByRole('alert')).toContainText('could not confirm the goal save');
  await expect(title).toHaveValue('Preserved preparation');
  expect(state().goals.find(item => item.id === goal.id)?.title).toBe('Preserved preparation');
  await page.unroute('**/*.data*');
  await title.fill('Stale local proposal');
  await page.getByRole('button', { name: 'Save goal draft', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'changed elsewhere' }).first()).toBeVisible();
  await expect(title).toHaveValue('Stale local proposal');
  await page.getByRole('button', { name: 'Cancel preparation' }).click();
  await page.reload(); await ready(page);
  expect(state().goals.find(item => item.id === goal.id)).toMatchObject({ status: 'draft', title: 'Preserved preparation' });
  expect(state().runs.filter(item => item.goalId === goal.id)).toHaveLength(0);
});
