import { capture, expect, goalAttempts, reload, runtime, scenarioScope, state, test, visit } from './fixtures';

test('activity history is bounded, keyboard navigable and scoped without losing old recovery facts', async ({ page, scenario }, testInfo) => {
  const scope = scenarioScope(scenario);
  await visit(page, `/projects/${scenario.launchProject}/goals/new${scope}`);
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill(`History recovery ${scenario.id}`);
  await page.getByRole('combobox', { name: 'Sendero', exact: true }).selectOption(scenario.prerequisiteVersionId);
  await page.getByRole('button', { name: 'Create goal', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Start goal', exact: true })).toBeVisible();
  const goal = state().goals.find(item => item.title === `History recovery ${scenario.id}`)!;
  await page.getByRole('button', { name: 'Start goal', exact: true }).click();
  await page.getByRole('link', { name: 'Review ready activations' }).click();
  await page.getByRole('button', { name: 'Dispatch all' }).click();
  await expect.poll(() => goalAttempts(goal.id).length).toBe(1);
  const attempt = goalAttempts(goal.id)[0]!;
  runtime('host-claim', attempt.id); runtime('host-start', attempt.id);
  runtime('host-reconcile-unknown', attempt.id);
  runtime('prepare-history', scenario.id);
  const before = state();
  // Synthetic noise follows the real recovery observation so the latest page excludes it.
  await visit(page, `/events${scope}`);
  const list = page.getByRole('list', { name: 'Activity events' });
  await expect(list.getByRole('listitem')).toHaveCount(50);
  const firstIds = await list.locator('article').evaluateAll(elements => elements.map(element => element.getAttribute('data-event-id')));
  expect(firstIds.every(id => id?.startsWith(`history-${scenario.id}-`))).toBe(true);
  const older = page.getByRole('link', { name: 'Older events', exact: true });
  await older.focus(); await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: 'Activity history' })).toBeFocused();
  await expect(list.getByRole('listitem')).toHaveCount(50);
  const secondIds = await list.locator('article').evaluateAll(elements => elements.map(element => element.getAttribute('data-event-id')));
  expect(secondIds.some(id => firstIds.includes(id))).toBe(false);
  const olderUrl = page.url();
  await reload(page);
  expect(await list.locator('article').evaluateAll(elements => elements.map(element => element.getAttribute('data-event-id')))).toEqual(secondIds);
  await page.getByText('Event details', { exact: true }).first().click();
  await expect(list.locator('pre').first()).toContainText('Fixture recorded event');
  await page.getByRole('heading', { name: 'Activity & events', exact: true }).scrollIntoViewIfNeeded();
  await capture(page, testInfo, 'activity-history-desktop-1440x1000');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await capture(page, testInfo, 'activity-history-mobile-390x844');
  await page.getByRole('link', { name: 'Newer events', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Activity history' })).toBeFocused();
  expect(await list.locator('article').evaluateAll(elements => elements.map(element => element.getAttribute('data-event-id')))).toEqual(firstIds);
  await page.getByRole('link', { name: 'Latest activity', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Latest activity' })).toBeFocused();
  await visit(page, olderUrl);
  // Changing scope discards the cursor and paginates the matching events first.
  await page.getByRole('combobox', { name: 'Project', exact: true }).selectOption(scenario.campaignProject);
  await expect(list.getByRole('listitem')).toHaveCount(21); // project creation plus 20 fixture events
  expect(new URL(page.url()).searchParams.has('cursor')).toBe(false);
  await visit(page, `/events?project=${scenario.launchProject}&cursor=broken&history=older`);
  await expect(page.getByRole('status')).toContainText('position is invalid');
  await expect(list.getByRole('listitem')).toHaveCount(50);
  await visit(page, `/events?project=missing-${scenario.id}`);
  await expect(page.getByRole('heading', { name: 'No events in this scope' })).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await visit(page, `/projects/${scenario.launchProject}/runs/attempts/${attempt.id}${scope}`);
  await page.getByText('Host and session records', { exact: true }).click();
  await expect(page.getByText('Recovery observation: Deterministic fixture inspection: unknown', { exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Keep recovery blocked' })).toBeVisible();
  await visit(page, `/projects/${scenario.launchProject}/canvas/goals/${goal.id}/attempts/${attempt.id}${scope}`);
  await expect(page.locator('.event-preview').getByText('fixture / history', { exact: true })).toHaveCount(6);
  await page.getByText('Host and session records', { exact: true }).click();
  await expect(page.getByText('Recovery observation: Deterministic fixture inspection: unknown', { exact: true })).toBeVisible();
  const after = state();
  expect(after.eventCount).toBe(before.eventCount);
  expect(after.claims).toEqual(before.claims);
  expect(after.attempts).toEqual(before.attempts);
  expect(after.runs).toEqual(before.runs);
});
