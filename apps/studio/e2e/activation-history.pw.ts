import { capture, expect, goalAttempts, ready, runtime, scenarioScope, state, test, visit } from './fixtures';

test('pages settled graph visits while retaining unresolved work and exact old evidence', async ({ page, scenario }, testInfo) => {
  const scope = scenarioScope(scenario);
  await visit(page, `/projects/${scenario.launchProject}/goals/new${scope}`);
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill(`Visit recovery ${scenario.id}`);
  await page.getByRole('combobox', { name: 'Sendero', exact: true }).selectOption(scenario.prerequisiteVersionId);
  await page.getByRole('button', { name: 'Create goal', exact: true }).click();
  const goal = state().goals.find(item => item.title === `Visit recovery ${scenario.id}`)!;
  await page.getByRole('button', { name: 'Start goal', exact: true }).click();
  await page.getByRole('link', { name: 'Review ready activations' }).click();
  await page.getByRole('button', { name: 'Dispatch all' }).click();
  await expect.poll(() => goalAttempts(goal.id).length).toBe(1);
  const active = goalAttempts(goal.id)[0]!;
  runtime('host-claim', active.id); runtime('host-start', active.id); runtime('host-reconcile-unknown', active.id);
  runtime('prepare-activation-history', goal.id);
  const before = state();
  await visit(page, `/projects/${scenario.launchProject}/runs/attempts/${active.id}${scope}`);
  const visits = page.getByRole('region', { name: 'Activations and branches', exact: true });
  const settled = visits.getByLabel('Settled visits', { exact: true });
  await expect(settled.getByRole('link')).toHaveCount(30);
  await expect(visits.getByLabel('Current visits', { exact: true }).getByRole('link')).toHaveCount(1);
  await expect(page.getByRole('heading', { name: 'Keep recovery blocked' })).toBeVisible();
  await visits.getByRole('heading', { name: 'Settled visit history' }).scrollIntoViewIfNeeded();
  await capture(page, testInfo, 'activation-history-desktop-1440x1000');
  const newer = await settled.getByRole('link').evaluateAll(links => links.map(link => new URL(link.getAttribute('href')!, location.href).pathname));
  await visits.getByRole('link', { name: 'Older visits', exact: true }).focus();
  await page.keyboard.press('Enter'); await ready(page);
  await expect(visits.getByRole('heading', { name: 'Settled visit history' })).toBeFocused();
  const secondPage = page.url();
  await settled.getByRole('link').nth(2).click(); await ready(page);
  await expect(page.getByText('Visit proof 92', { exact: true })).toBeVisible();
  await page.reload(); await ready(page);
  await expect(page.getByText('Visit proof 92', { exact: true })).toBeVisible();
  await page.goBack(); await ready(page);
  expect(page.url()).toBe(secondPage);
  await expect(page.getByRole('heading', { name: 'Keep recovery blocked' })).toBeVisible();
  await page.goForward(); await ready(page);
  await expect(page.getByText('Visit proof 92', { exact: true })).toBeVisible();
  await expect(visits.getByLabel('Current visits', { exact: true }).getByRole('link')).toHaveCount(1);
  await visits.getByRole('link', { name: 'Newer visits', exact: true }).click(); await ready(page);
  expect(await settled.getByRole('link').evaluateAll(links => links.map(link => new URL(link.getAttribute('href')!, location.href).pathname))).toEqual(newer);
  await visit(page, secondPage);
  const seen = new Set<string>();
  for (;;) {
    for (const href of await settled.getByRole('link').evaluateAll(links => links.map(link => new URL(link.getAttribute('href')!, location.href).pathname))) { expect(seen.has(href)).toBe(false); seen.add(href); }
    if (!await visits.getByRole('link', { name: 'Older visits', exact: true }).count()) break;
    await visits.getByRole('link', { name: 'Older visits', exact: true }).click(); await ready(page);
  }
  expect(seen.size).toBe(95);
  await visit(page, `/projects/${scenario.launchProject}/runs/attempts/visit-attempt-${goal.id}-2${scope}`);
  await expect(settled.locator('a[aria-current="true"]')).toContainText('visit 3');
  await expect(settled.locator('a[aria-current="true"]')).toContainText('fixture-fork-generation');
  await expect(page.getByText('Visit proof 2', { exact: true })).toBeVisible();
  await visits.getByRole('link', { name: 'Latest visits', exact: true }).click(); await ready(page);
  await expect(visits.getByRole('status')).toContainText('selected attempt is outside');
  await expect(settled.getByRole('link').first()).toContainText('visit 125');
  await visits.getByRole('link', { name: 'Show selected visit', exact: true }).click(); await ready(page);
  await expect(settled.locator('a[aria-current="true"]')).toContainText('visit 3');
  await page.setViewportSize({ width: 390, height: 844 }); await page.reload(); await ready(page);
  await visits.getByRole('heading', { name: 'Settled visit history' }).scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const nextBounds = await visits.getByRole('link', { name: 'Newer visits', exact: true }).boundingBox();
  expect(nextBounds!.height).toBeGreaterThanOrEqual(40);
  await capture(page, testInfo, 'activation-history-mobile-390x844');
  const invalid = new URL(page.url()); invalid.searchParams.set('visitCursor', 'broken'); invalid.searchParams.set('visitHistory', 'older');
  await visit(page, invalid.toString());
  await expect(visits.getByRole('status').first()).toContainText('position is invalid');
  expect(state()).toEqual(before);
});
