import { capture, expect, ready, reload, scenarioScope, state, test, visit, workflowCreated } from './fixtures';
for (const width of [1440, 390]) test(`preserves published agent guidance after a live definition edit at ${width}px`, async ({ page, scenario }, testInfo) => {
  await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 });
  const scope = scenarioScope(scenario), slug = `pinned-agent-${scenario.id}`;
  const originalName = `Original pinned executor ${scenario.id.slice(0, 8)}`;
  const editedName = `Later current executor ${scenario.id.slice(0, 8)}`;
  await visit(page, `/agents/new${scope}`);
  await page.getByRole('textbox', { name: /^Name\b/ }).fill(originalName);
  await page.getByRole('textbox', { name: 'Slug', exact: true }).fill(slug);
  await page.getByRole('textbox', { name: 'Instructions', exact: true }).fill('Synthetic original pinned instructions');
  await page.getByRole('button', { name: 'Create agent', exact: true }).click();
  await expect(page.getByText('Agent created.', { exact: true })).toBeVisible(); await ready(page);
  const agent = state().agents.find(item => item.slug === slug)!;
  await visit(page, `/senderos/new${scope}`);
  await page.getByRole('combobox', { name: 'Authoring method' }).selectOption('import');
  await page.getByRole('textbox', { name: 'Sendero JSON' }).fill(JSON.stringify({ slug: `pinned-inspection-${scenario.id}`, name: 'Pinned inspection audit', nodes: [
    { key: 'start', kind: 'start', label: 'Begin' },
    { key: 'worker', kind: 'agent', label: 'Inspect pinned policy', agentSlug: slug, executionObjective: 'Synthetic inspection only' },
    { key: 'end', kind: 'end', label: 'End' },
  ], edges: [{ key: 'begin', source: 'start', target: 'worker', name: 'Begin' }, { key: 'finish', source: 'worker', target: 'end', name: 'Finish' }] }));
  await page.getByRole('button', { name: 'Import draft', exact: true }).click(); await workflowCreated(page);
  const workflowId = new URL(page.url()).pathname.split('/').at(-1)!;
  await page.getByRole('button', { name: 'Validate & publish draft' }).click();
  await expect(page.getByRole('button', { name: 'Create editable draft' })).toBeVisible();
  const published = state(), version = published.versions.find(item => item.senderoId === workflowId)!;
  const node = published.nodes.find(item => item.senderoVersionId === version.id && item.kind === 'agent')!;
  expect(JSON.parse(node.agentSnapshotJson!).instructions).toBe('Synthetic original pinned instructions');
  await visit(page, `/projects/${scenario.launchProject}/goals/new${scope}`);
  await page.getByRole('textbox', { name: 'Title', exact: true }).fill(`Pinned inspection goal ${scenario.id}`);
  await page.getByLabel('Category', { exact: true }).fill('feature');
  await page.getByRole('textbox', { name: 'Specification', exact: true }).fill('Synthetic inspection only');
  await page.getByRole('combobox', { name: 'Sendero', exact: true }).selectOption(version.id);
  await page.getByRole('button', { name: 'Create goal', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Edit goal', exact: true })).toBeVisible();
  const goal = state().goals.find(item => item.title === `Pinned inspection goal ${scenario.id}`)!;
  await visit(page, `/agents/${agent.id}${scope}`);
  await page.getByRole('textbox', { name: /^Name\b/ }).fill(editedName);
  await page.getByRole('textbox', { name: 'Instructions', exact: true }).fill('Synthetic later current instructions');
  await page.getByRole('button', { name: 'Save agent', exact: true }).click();
  await expect.poll(() => state().agents.find(item => item.id === agent.id)?.name).toBe(editedName);
  const before = state();
  await visit(page, `/senderos/${workflowId}/nodes/${node.id}${scope}`);
  const inspector = page.locator('.context-inspector');
  const workflowUrl = page.url();
  const nodeLink = page.getByRole('link', { name: 'Inspect agent Inspect pinned policy', exact: true });
  await expect(nodeLink).toHaveText(/Original pinned executor/);
  await expect(nodeLink).toHaveAttribute('title', new RegExp(`Pinned agent: ${originalName}`));
  const instructions = inspector.getByText('Pinned instructions', { exact: true });
  await instructions.focus(); await expect(instructions).toBeFocused(); await page.keyboard.press('Enter');
  await expect(inspector.getByText('Synthetic original pinned instructions', { exact: true })).toBeVisible();
  const actualText = await inspector.innerText();
  await testInfo.attach('pinned-vs-current-inspector', { body: JSON.stringify({ actualText, current: before.agents.find(item => item.id === agent.id), pinned: JSON.parse(node.agentSnapshotJson!) }, null, 2), contentType: 'application/json' });
  await capture(page, testInfo, `pinned-agent-inspector-final-${width}`);
  await reload(page); expect(state()).toEqual(before);
  expect(actualText).toContain(originalName);
  expect(actualText).toContain('Pinned instructions');
  expect(actualText).toContain('Synthetic original pinned instructions');
  await inspector.getByRole('link', { name: 'Close inspector', exact: true }).click(); await ready(page);
  await nodeLink.focus(); await expect(nodeLink).toBeFocused(); await page.keyboard.press('Enter');
  await expect(page).toHaveURL(workflowUrl); await ready(page);
  expect(state()).toEqual(before);
  await visit(page, `/projects/${scenario.launchProject}/canvas/goals/${goal.id}${scope}`);
  const goalCanvasUrl = page.url();
  await nodeLink.click(); await ready(page);
  await inspector.getByText('Pinned instructions', { exact: true }).click();
  await expect(inspector.getByText('Synthetic original pinned instructions', { exact: true })).toBeVisible();
  const goalUrl = page.url();
  await expect(nodeLink).toHaveText(/Original pinned executor/);
  const goalText = await inspector.innerText();
  await testInfo.attach('goal-pinned-vs-current-inspector', { body: goalText, contentType: 'text/plain' });
  await capture(page, testInfo, `pinned-goal-inspector-final-${width}`);
  expect(goalText).toContain(originalName);
  expect(goalText).toContain('Pinned instructions');
  expect(goalText).toContain('Synthetic original pinned instructions');
  await reload(page); expect(state()).toEqual(before);
  await expect(inspector.getByText('Pinned agent', { exact: true }).locator('..').getByText(originalName, { exact: true })).toBeVisible();
  await page.goBack(); await ready(page);
  expect(page.url()).toBe(goalCanvasUrl);
  await page.goBack(); await ready(page); expect(page.url()).toBe(workflowUrl);
  await expect(inspector.getByRole('heading', { name: originalName, exact: true })).toBeVisible();
  await page.goForward(); await ready(page); expect(page.url()).toBe(goalCanvasUrl);
  await page.goForward(); await ready(page); expect(page.url()).toBe(goalUrl);
  expect(state()).toEqual(before);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
