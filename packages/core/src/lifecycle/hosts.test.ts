test('claim is distinct from start; independent session and declared workspace are required', async () => {
  const { home, attemptId, hostApi } = await strictHostFixture();
  await expect(startAttempt({ attemptId, token: 'none', externalSessionId: 'a', parentSessionId: 'b', workingPath: '/remote/workspace' }, home)).rejects.toMatchObject({ code: 'CLAIM_REQUIRED' });
  await expect(updateRunAttempt(attemptId, { status: 'succeeded' }, home)).rejects.toMatchObject({ code: 'CLAIM_REQUIRED' });
  const claim = await hostApi.claim();
  expect(claim.started).toBe(false);
  const claimed = await getRunAttempt(attemptId, home);
  expect(claimed).toMatchObject({ status: 'queued', startedAt: null, ownerId: 'host-a', harness: 'custom-tool', workingPath: '/remote/workspace' });
  expect(JSON.stringify(claimed)).not.toContain(claim.token);
  expect(claimed!.preflight).toMatchObject({ eligible: true, declaredCapabilities: ['independent_session', 'shell'] });
  await expect(updateRunAttempt(attemptId, { status: 'succeeded', token: claim.token }, home)).rejects.toMatchObject({ code: 'SESSION_REQUIRED' });
  await expect(hostApi.start(claim.token, { externalSessionId: 'main-1' })).rejects.toMatchObject({ code: 'INDEPENDENT_SESSION_REQUIRED' });
  await expect(hostApi.start(claim.token, { workingPath: '/unavailable' })).rejects.toMatchObject({ code: 'PREFLIGHT_FAILED' });
  await expect(abandonAttempt({ attemptId, token: 'stale', confirmedStopped: true, reason: 'Old host assertion' }, home)).rejects.toMatchObject({ code: 'STALE_OWNER' });
  const started = await hostApi.start(claim.token, { resumeCommand: 'host resume worker-1' });
  expect(started.status).toBe('running');
  expect((await hostApi.start(claim.token)).externalSessionId).toBe('worker-1');
  await expect(hostApi.start(claim.token, { externalSessionId: 'other' })).rejects.toMatchObject({ code: 'SESSION_CONFLICT' });
  expect((await heartbeatAttempt({ attemptId, token: claim.token }, home)).cancellationRequested).toBe(false);
});
test('expired strict claims require persisted active inspection and keep unknown or missing sessions blocked', async () => {
  const { home, attemptId, db, hostApi } = await strictHostFixture(true);
  const claim = await hostApi.claim();
  await hostApi.start(claim.token);
  await db.update(attemptClaims).set({ leaseExpiresAt: '2000-01-01' }).where(eq(attemptClaims.attemptId, attemptId));
  const remote = scopedApi({ reconcile: (outcome: 'active' | 'missing' | 'unknown', extras: Partial<Parameters<typeof reconcileAttempt>[0]> = {}) => reconcileAttempt({ attemptId, ownerId: 'host-a', outcome, details: 'Inspected external process registry', externalSessionId: 'worker-1', ...extras }, home), heartbeat: (token: string) => heartbeatAttempt({ attemptId, token }, home) }, 'remote');
  await expect(hostApi.claim()).rejects.toMatchObject({ code: 'RECLAIM_REQUIRED' });
  await expect(hostApi.claim({ reclaim: true })).rejects.toMatchObject({ code: 'RECOVERY_REQUIRED' });
  expect((await remote.reconcile('unknown')).nextAction).toContain('Keep blocked');
  await expect(hostApi.claim({ reclaim: true })).rejects.toMatchObject({ code: 'RECOVERY_REQUIRED' });
  expect((await remote.reconcile('missing')).nextAction).toContain('abandon');
  await expect(hostApi.claim({ reclaim: true })).rejects.toMatchObject({ code: 'RECOVERY_REQUIRED' });
  await expect(remote.reconcile('active', { externalSessionId: 'wrong' })).rejects.toMatchObject({ code: 'SESSION_CONFLICT' });
  expect((await remote.reconcile('active')).nextAction).toContain('existing session');
  const reclaimed = await hostApi.claim({ reclaim: true });
  expect(reclaimed.token).not.toBe(claim.token);
  expect(reclaimed.started).toBe(true);
  await expect(remote.heartbeat(claim.token)).rejects.toMatchObject({ code: 'NOT_FOUND' });
  expect((await remote.heartbeat(reclaimed.token)).cancellationRequested).toBe(false);
});
test('recovery validates owner, inspection details, outcome, and live ownership', async () => {
  const { home, attemptId, hostApi } = await strictHostFixture();
  const claim = await hostApi.claim(); await hostApi.start(claim.token);
  const inspect = (extra: Partial<Parameters<typeof reconcileAttempt>[0]> = {}) => reconcileAttempt({ attemptId, ownerId: 'host-a', outcome: 'unknown', details: 'Cannot inspect remote process', ...extra }, home);
  await expect(inspect()).rejects.toMatchObject({ code: 'ALREADY_CLAIMED' });
  await expect(inspect({ token: claim.token, details: '' })).rejects.toMatchObject({ code: 'INVALID_INPUT' });
  await expect(inspect({ token: claim.token, outcome: 'invalid' as 'unknown' })).rejects.toMatchObject({ code: 'INVALID_INPUT' });
  await registerHost({ id: 'host-b', name: 'Host B', capabilities: [] }, home);
  await expect(inspect({ ownerId: 'host-b' })).rejects.toMatchObject({ code: 'RECOVERY_HOST_REQUIRED' });
  await expect(inspect({ token: claim.token, outcome: 'finished', externalSessionId: 'worker-1' })).rejects.toMatchObject({ code: 'RESULT_REQUIRED' });
  expect((await inspect({ token: claim.token })).outcome).toBe('unknown');
});
test('finished inspection reports atomically and fences stale owner; missing inspection permits explicit abandon', async () => {
  const { home, attemptId, hostApi, db, goalId } = await strictHostFixture(true);
  const claim = await hostApi.claim(); await hostApi.start(claim.token);
  await db.update(attemptClaims).set({ leaseExpiresAt: '2000-01-01' }).where(eq(attemptClaims.attemptId, attemptId));
  const remote = scopedApi({ finish: () => reconcileAttempt({ attemptId, ownerId: 'host-a', outcome: 'finished', externalSessionId: 'worker-1', details: 'Read durable worker result', status: 'failed', result: { reason: 'tool error' } }, home), update: () => updateRunAttempt(attemptId, { token: claim.token, status: 'failed' }, home), discover: () => discoverHostAttempts('host-a', home) }, 'remote');
  expect((await remote.finish()).status).toBe('failed');
  expect((await getRunAttempt(attemptId, home))!.recoveryOutcome).toBe('finished');
  await expect(remote.update()).rejects.toMatchObject({ code: 'NOT_FOUND' });
  expect(await remote.discover()).toHaveLength(0);
  expect((await remote.finish()).status).toBe('failed');
  const retry = await dispatchRun({ goalId }, home);
  // Retried fresh-runtime work keeps the strict host protocol and the same remote grant.
  const retryClaim = await hostApi.claim({ attemptId: retry.attemptId });
  expect((await abandonAttempt({ attemptId: retry.attemptId, token: retryClaim.token, confirmedStopped: true, reason: 'Process registry confirms exit' }, home)).status).toBe('failed');
});
test('start refuses duplicate active session identities and cancellation, and expired ownership cannot start', async () => {
  const { home, attemptId, hostApi, db, goalId } = await strictHostFixture();
  const claim = await hostApi.claim();
  const attempt = (await db.select().from(runAttempts).where(eq(runAttempts.id, attemptId)))[0]!;
  await db.insert(runAttempts).values({ ...attempt, id: 'duplicate', externalSessionId: 'worker-1', status: 'running', hostEnvironmentName: 'host-a' });
  await expect(hostApi.start(claim.token)).rejects.toMatchObject({ code: 'SESSION_IN_USE' });
  await db.delete(runAttempts).where(eq(runAttempts.id, 'duplicate'));
  await db.update(attemptClaims).set({ leaseExpiresAt: '2000-01-01' }).where(eq(attemptClaims.attemptId, attemptId));
  await expect(hostApi.start(claim.token)).rejects.toMatchObject({ code: 'LEASE_EXPIRED' });
  await db.update(attemptClaims).set({ leaseExpiresAt: new Date(Date.now() + 60_000).toISOString() }).where(eq(attemptClaims.attemptId, attemptId));
  await cancelGoal(goalId, home);
  await expect(hostApi.start(claim.token)).rejects.toMatchObject({ code: 'CANCELLATION_REQUESTED' });
  expect((await heartbeatAttempt({ attemptId, token: claim.token }, home)).cancellationRequested).toBe(true);
  await updateRunAttempt(attemptId, { status: 'canceled', token: claim.token }, home);
  await expect(hostApi.start(claim.token)).rejects.toMatchObject({ code: 'TERMINAL_ATTEMPT' });
});

test('external session IDs are isolated by host, and actual session independence is a host declaration', async () => {
  const { home, attemptId, project, hostApi, db } = await strictHostFixture();
  const first = await hostApi.claim(); await hostApi.start(first.token);
  const goal = await createGoal({ home, projectId: project.id, title: 'Second host session' });
  await activateGoal(goal.id, home);
  const other = await dispatchRun({ goalId: goal.id }, home);
  expect((await getRunAttempt(other.attemptId, home))!.protocolVersion).toBe(2);
  await registerHost({ id: 'host-b', name: 'Host B', capabilities: ['independent_session'] }, home);
  await grantHostWorkspace({ hostId: 'host-b', projectId: project.id, workspaceRef: 'repo' }, home);
  await declareHostWorkspace({ hostId: 'host-b', projectId: project.id, available: true, workingPath: '/second' }, home);
  const second = await claimAttempt({ attemptId: other.attemptId, ownerId: 'host-b' }, home);
  const started = await startAttempt({ attemptId: other.attemptId, token: second.token, externalSessionId: 'worker-1', parentSessionId: 'main-1', workingPath: '/second' }, home);
  expect(started.externalSessionId).toBe((await getRunAttempt(attemptId, home))!.externalSessionId);
  expect(started.hostEnvironmentName).not.toBe((await getRunAttempt(attemptId, home))!.hostEnvironmentName);
});

import { grantHostWorkspace } from './host-registry';
import { resumeAttempt } from '../commands/runs/resume-attempt';
test('revoked workspace access drains recorded sessions but does not permit a new launch', async () => {
  const { home, attemptId, project, hostApi } = await strictHostFixture(true);
  const claim = await hostApi.claim(); await hostApi.start(claim.token);
  await grantHostWorkspace({ hostId: 'host-a', projectId: project.id, workspaceRef: 'repo', revoke: true }, home);
  await hostApi.register([], false);
  const remote = scopedApi({ discover: () => discoverHostAttempts('host-a', home), heartbeat: () => heartbeatAttempt({ attemptId, token: claim.token }, home), finish: () => updateRunAttempt(attemptId, { token: claim.token, status: 'failed', failureSummary: 'Access withdrawn; host stopped worker' }, home), resume: () => resumeAttempt(attemptId, home) }, 'remote');
  expect((await remote.heartbeat()).cancellationRequested).toBe(false);
  expect((await remote.discover())[0]).toMatchObject({ attemptId, ownerId: 'host-a', preflight: { eligible: false, blockers: expect.arrayContaining(['workspace_not_granted', 'host_disabled']) } });
  const resume = await remote.resume();
  expect(resume.packet.workingPath).toBe('/remote/workspace');
  expect(JSON.stringify(resume)).not.toContain(claim.token);
  expect((await remote.finish()).status).toBe('failed');
});
